SELECT E.NOM
FROM EMPLOYE E
WHERE EXISTS (
    SELECT 1
    FROM POSTES P1
    JOIN POSTES P2 ON P1.CODQUAL = P2.CODQUAL AND P1.UNITCOD = P2.UNITCOD
    WHERE P2.UNITCOD = E.UNITCOD
      AND P2.CODQUAL = E.JOBCODE
      AND P1.CODQUAL = (SELECT JOBCODE FROM EMPLOYE WHERE NOM='LEVITT')
);
