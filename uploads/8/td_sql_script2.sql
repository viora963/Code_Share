FROM EMPLOYE E
WHERE E.UNITCOD='2111'
AND (
       E.QUALIFPR IN (SELECT QUALIFPR FROM EMPLOYE WHERE UNITCOD='2123')
    OR E.EMPCOD IN (
        SELECT EMPCOD FROM EMPSQUAL
        WHERE CODQUAL IN (
            SELECT CODQUAL FROM EMPSQUAL WHERE EMPCOD IN (
                SELECT EMPCOD FROM EMPLOYE WHERE UNITCOD='2123'
            )
        )
    )
);
