-- 22
SELECT TOP 1 JOBCODE, Q.QUALIBEL,
       AVG(SALAIRE) AS MOYENNE
FROM EMPLOYE E
JOIN QUALIF Q ON Q.CODQUAL = E.JOBCODE
GROUP BY JOBCODE, Q.QUALIBEL
ORDER BY MOYENNE ASC;

